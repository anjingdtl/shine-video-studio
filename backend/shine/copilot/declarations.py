"""The single declaration of what Shine's copilot may know and do.

Every row here references real product code: a real FastAPI route, a real
Pydantic request model, a real service/executor and a real read-back ledger.
The build generator turns these rows into:

* the versioned project knowledge index,
* the capability registry served to the UI,
* the parameter contract the natural-language planner and the frontend share,
* the compatibility report CI checks on every change.

Adding a product feature therefore means: implement it, declare it once here
(or in a reviewed declaration module), and let the build produce the copilot
contracts.  A declaration never grants execution by itself: the action must be
``AVAILABLE`` *and* bound to a reviewed dispatcher in ``support.actions``.

Nothing in this module may import business services at module import time.
"""
